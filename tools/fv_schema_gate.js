#!/usr/bin/env node
/**
 * fv_schema_gate.js — every field in MAPS must have a real column in Postgres.
 *
 * Two production incidents came from this gap being guarded by human memory:
 * movements.photos was mapped but never created (every movement upsert failed
 * silently for ~14 h, 2026-08-01, rows permanently lost), and status_events
 * shipped without show_id. This gate makes the rule mechanical: preflight
 * refuses to clear a build whose MAPS names a column Postgres doesn't have.
 *
 * HOW IT GETS THE REAL SCHEMA WITHOUT CREDENTIALS
 * -----------------------------------------------
 * `GET /rest/v1/<table>?select=<cols>&limit=0` with the public anon key
 * returns 200 when every column exists and Postgres 42703 NAMING the missing
 * column when one doesn't — RLS hides rows, not column errors. (The OpenAPI
 * endpoint is a dead end: empty definitions for the anon role.)
 *
 * MODES — the gate never silently skips:
 *   live     network up:   probe every table, then rewrite schema.snapshot.json
 *            (the snapshot is machine-generated; never edit it by hand)
 *   snapshot network down: verify mapped ⊆ committed snapshot, loud banner
 *   neither  no network and no snapshot -> exit 1 (refuses to vouch blind)
 *
 * Checked per table: every value of MAPS[t].m PLUS MAPS[t].ro — read-only
 * columns are the same drift class (received_at was mapped on three tables it
 * didn't exist on, found 2026-08-01).
 *
 * Usage:
 *   node tools/fv_schema_gate.js              (gate; run by preflight)
 *   node tools/fv_schema_gate.js --selftest   (proves 42703 detection live)
 * Zero npm dependencies. FV_URL / FV_ANON_KEY override the defaults.
 */
